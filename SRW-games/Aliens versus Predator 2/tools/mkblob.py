#!/usr/bin/env python3
"""mkblob.py: the recompiled code (SRW's modules + the runtime's asm stubs, ELF x86-64 objects) as one image at a fixed
address, for programs that can't link it themselves at a low address (macOS: 64-bit Mach-O executables live above
4 GB and Mach-O has no 32-bit absolute relocations; the recompiled code addresses everything with 32 bits).

  mkblob.py --base 0x20000000 --name SR-AvP2 --asmsyms asmsyms.h --out <dir> <objects...>

Every symbol the objects use but don't define is a C function of the runtime (checked): the image gets a thunk for
each (jmp [slot]) and the program fills the slots when it loads the image (blob.c). The program finds the image's
symbols it uses (asmsyms.h's list) in blob_addr. The calling convention inside is System V AMD64 (the objects' elf64
branches), the same on Linux and macOS.

Writes into <dir>: <name>.blob (the image's bytes from the base), blob_link_<name>.cpp (blob_info, blob_imports,
blob_addr: compiled into the program), <name>.blobmap (text: every symbol), <name>.blob.elf (for debugging).
Needs nasm, GNU ld, objcopy, nm (binutils; on macOS: x86_64-elf-binutils)."""
import argparse, os, re, subprocess, sys

def run(args, **kw):
    r = subprocess.run(args, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.exit('mkblob: %s failed:\n%s%s' % (' '.join(args[:3]), r.stdout, r.stderr))
    return r.stdout

def tool(name):
    # GNU binutils for ELF: the host's on Linux, x86_64-elf-* elsewhere
    for cand in (os.environ.get('BLOB_' + name.upper()), 'x86_64-elf-' + name, 'x86_64-linux-gnu-' + name, name):
        if cand and subprocess.run(['sh', '-c', 'command -v "%s"' % cand], capture_output=True).returncode == 0:
            return cand
    sys.exit('mkblob: no %s (GNU binutils for x86-64 ELF)' % name)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--base', default='0x20000000')
    ap.add_argument('--name', required=True)
    ap.add_argument('--asmsyms', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('objects', nargs='+')
    a = ap.parse_args()
    base = int(a.base, 0)
    ld, objcopy, nm = tool('ld'), tool('objcopy'), tool('nm')
    os.makedirs(a.out, exist_ok=True)
    pre = os.path.join(a.out, a.name)

    # the objects together; what they need from outside
    run([ld, '-r', '-o', pre + '.combined.o'] + a.objects)
    undefined = sorted(set(l.split()[-1] for l in run([nm, '-u', pre + '.combined.o']).splitlines() if l.strip()))
    for u in undefined:
        if not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', u):
            sys.exit('mkblob: unexpected undefined symbol %r' % u)

    # thunks: jmp [slot]; the slots in their own section (written once at load time)
    with open(pre + '.thunks.asm', 'w') as f:
        f.write('; generated by mkblob.py: the C runtime\'s functions the recompiled code calls\ndefault rel\n'
                'section .text progbits alloc exec nowrite align=16\n')
        for u in undefined:
            f.write('global %s\nalign 8\n%s: jmp qword [__blob_slot_%s]\n' % (u, u, u))
        f.write('section .blobslots progbits alloc noexec write align=8\n')
        for u in undefined:
            f.write('global __blob_slot_%s\n__blob_slot_%s: dq 0\n' % (u, u))
        f.write('section .note.GNU-stack noalloc noexec nowrite progbits\n')
    run(['nasm', '-felf64', '-o', pre + '.thunks.o', pre + '.thunks.asm'])

    # one image from the base: code, read-only data, the slots and data, zeroed data
    with open(pre + '.ld', 'w') as f:
        f.write('''ENTRY(__blob_start)
SECTIONS
{
  . = 0x%x;
  __blob_start = .;
  .text : { *(.text) *(.text.*) }
  . = ALIGN(0x4000);
  __blob_text_end = .;
  .rodata : { *(.rodata) *(.rodata.*) *(.rdata) *(.rdata.*) }
  . = ALIGN(0x4000);
  .data : { *(.blobslots) *(.data) *(.data.*) }
  __blob_file_end = .;
  .bss : { *(.bss) *(.bss.*) *(COMMON) }
  . = ALIGN(0x4000);
  __blob_end = .;
  /DISCARD/ : { *(.note.GNU-stack) *(.comment) *(.eh_frame) *(.note.*) }
}
''' % base)
    run([ld, '-static', '-nostdlib', '--no-undefined', '-T', pre + '.ld', '-o', pre + '.blob.elf', pre + '.combined.o', pre + '.thunks.o'])
    run([objcopy, '-O', 'binary', '--only-section=.text', '--only-section=.rodata', '--only-section=.data',
         pre + '.blob.elf', pre + '.blob'])

    syms = {}
    for l in run([nm, pre + '.blob.elf']).splitlines():
        p = l.split()
        if len(p) == 3:
            syms[p[2]] = int(p[0], 16)
    start, text_end, file_end, end = syms['__blob_start'], syms['__blob_text_end'], syms['__blob_file_end'], syms['__blob_end']
    if start != base:
        sys.exit('mkblob: the image starts at 0x%x, not 0x%x' % (start, base))
    size = os.path.getsize(pre + '.blob')
    if size != file_end - base:
        sys.exit('mkblob: %s is %d bytes, expected %d' % (pre + '.blob', size, file_end - base))
    if end > 0x80000000:
        sys.exit('mkblob: the image ends above 2 GB (0x%x)' % end)

    # the program's side: asmsyms.h's symbols in its order, the slots with their functions
    hdr = open(a.asmsyms).read()
    m = re.search(r'#define ASM_SYMBOLS\(X\) \\\n((?:.*\\\n)*.*\n)', hdr)
    if not m:
        sys.exit('mkblob: no ASM_SYMBOLS list in ' + a.asmsyms)
    names = re.findall(r'X\(([A-Za-z0-9_]+)\)', m.group(1))
    missing = [n for n in names + ['c_call_asm_n', 'c_call_asm_this'] if n not in syms]
    if missing:
        sys.exit('mkblob: the image lacks ' + ', '.join(missing))
    with open(os.path.join(a.out, 'blob_link_%s.cpp' % a.name), 'w') as f:
        f.write('// generated by mkblob.py for %s.blob: don\'t edit\n#include <stdint.h>\n#include <stddef.h>\n' % a.name)
        # the declarations (blob.h, asmsyms.h) give the constants external linkage in C++
        f.write('#include "blob.h"\n#include "asmsyms.h"\n\nextern "C" {\n\n')
        f.write('const blob_info blob = { "%s.blob", 0x%xu, 0x%xu, 0x%xu, 0x%xu };\n\n' % (a.name, base, text_end - base, size, end - base))
        f.write('const uintptr_t blob_addr[] = {\n')
        for n in names:
            f.write('    0x%xu, // %s\n' % (syms[n], n))
        f.write('};\nconst uintptr_t blob_addr_c_call_asm_n = 0x%xu, blob_addr_c_call_asm_this = 0x%xu;\n\n' %
                (syms['c_call_asm_n'], syms['c_call_asm_this']))
        for u in undefined:
            f.write('void %s(void);\n' % u)
        f.write('\nconst blob_import blob_imports[] = {\n')
        for u in undefined:
            f.write('    { 0x%xu, (void (*)(void))%s },\n' % (syms['__blob_slot_' + u], u))
        f.write('};\nconst unsigned blob_nimports = %d;\n\n}\n' % len(undefined))
    with open(pre + '.blobmap', 'w') as f:
        f.write('base 0x%x text %d file %d size %d imports %d\n' % (base, text_end - base, size, end - base, len(undefined)))
        for n, v in sorted(syms.items(), key=lambda kv: kv[1]):
            f.write('%08x %s\n' % (v, n))
    for tmp in ('.combined.o', '.thunks.o'):
        os.remove(pre + tmp)
    print('mkblob: %s.blob: 0x%x-0x%x (code %d KB, file %d KB), %d imports, %d symbols for the program' %
          (pre, base, end, (text_end - base) // 1024, size // 1024, len(undefined), len(names)))

main()
