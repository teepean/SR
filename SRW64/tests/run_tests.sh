#! /bin/sh
#
# SRW64 tests
#
# Each test compiles a 64-bit Windows (or Linux) program, recompiles it with SRW64,
# builds the recompiled program and compares its output with the output of the original program.
#
# Requirements: nasm, MinGW-w64 (x86_64-w64-mingw32-gcc, dlltool, windres), wine, gcc, ld, python3
#               (static glibc for the Linux test - it is skipped when not available)
#
# Environment variables:
#   SRW64       - path to SRW64 executable (default: ../SRW64.exe relative to this script)
#   WORK        - work directory (default: new temporary directory)
#   WINDOWS_DIR - optional directory with original Windows executables (sort.exe, where.exe),
#                 for example /mnt/windows/Windows/System32
#   FH4_EXECUTABLES - optional list of executables built by Visual Studio 2019+ (with __CxxFrameHandler4),
#                 their C++ exception handling data is verified after recompilation
#

TESTS_DIR=$(cd "$(dirname "$0")" && pwd)
SRW64_DIR=$(dirname "$TESTS_DIR")
SRW64=${SRW64:-$SRW64_DIR/SRW64.exe}
export SRW64
WORK=${WORK:-$(mktemp -d "${TMPDIR:-/tmp}/srw64-tests.XXXXXX")}
SUPPORT_DIR=$SRW64_DIR/x64-support
REPAIR=$SRW64_DIR/../SRW64-games/template/repair_short_jumps.py
CROSS=${CROSS:-x86_64-w64-mingw32-}

export WINEDEBUG=-all
export WINEDLLOVERRIDES="mscoree,mshtml="

FAILED=0

check_tool()
{
    if ! command -v "$1" > /dev/null 2>&1; then
        echo "Missing tool: $1"
        exit 2
    fi
}

compare()
{
    if cmp -s "$1" "$2"; then
        echo "PASS: $3"
    else
        echo "FAIL: $3"
        FAILED=1
    fi
}

# assemble <format> <name> - assembles <name>.asm into <name>.<format>.o (repairs short jumps)
assemble()
{
    cp "$REPAIR" . || return 1
    PASS=0
    while :; do
        nasm -f $1 -O1 -w-number-overflow -i"$SUPPORT_DIR/" "$2.asm" -o "$2.$1.o" 2> a.a && return 0
        if grep "error" a.a | grep -q -v "short jump is out of range"; then
            grep "error" a.a | head -5
            return 1
        fi
        PASS=$((PASS + 1))
        [ $PASS -ge 10 ] && return 1
        python3 repair_short_jumps.py
    done
}

for tool in nasm "${CROSS}gcc" "${CROSS}dlltool" "${CROSS}windres" wine gcc python3; do
    check_tool "$tool"
done

if [ ! -x "$SRW64" ]; then
    echo "SRW64 executable not found: $SRW64 (build it with scons or build_gcc.sh)"
    exit 2
fi

echo "Work directory: $WORK"


# test 1: C program compiled by MinGW (CRT startup code, switch tables, function pointers, floating point, ...)
mkdir -p "$WORK/mingw_c"
cd "$WORK/mingw_c" || exit 1
if "${CROSS}gcc" -O2 -o test1.exe "$TESTS_DIR/mingw_c/test1.c" -lm; then
    wine ./test1.exe > expected.txt 2> /dev/null
    if RESULT=$("$TESTS_DIR/roundtrip_win64.sh" test1.exe "$WORK/mingw_c/srw64"); then
        wine "$RESULT" > actual.txt 2> /dev/null
        compare expected.txt actual.txt "MinGW C program (win64)"
    else
        echo "$RESULT"
        echo "FAIL: MinGW C program (win64) - recompilation failed"
        FAILED=1
    fi
else
    echo "FAIL: MinGW C program - compilation failed"
    FAILED=1
fi


# test 2: code patterns generated by MSVC (image relative jump tables and addressing) - win64 and elf64
mkdir -p "$WORK/msvc_patterns"
cd "$WORK/msvc_patterns" || exit 1
if nasm -f win64 "$TESTS_DIR/msvc_patterns/msvc_patterns.asm" -o msvc_patterns.obj &&
   "${CROSS}gcc" -O2 -nostdlib -ffreestanding -fno-builtin -mno-stack-arg-probe -Wl,-e,start "$TESTS_DIR/msvc_patterns/main.c" msvc_patterns.obj -lkernel32 -o patterns.exe
then
    wine ./patterns.exe > expected.txt 2> /dev/null
    if RESULT=$("$TESTS_DIR/roundtrip_win64.sh" patterns.exe "$WORK/msvc_patterns/srw64"); then
        wine "$RESULT" > actual_win64.txt 2> /dev/null
        compare expected.txt actual_win64.txt "MSVC code patterns (win64)"

        # the same assembler source compiled for Linux
        cd "$WORK/msvc_patterns/srw64" || exit 1
        if assemble elf64 patterns && gcc -no-pie -O2 "$TESTS_DIR/msvc_patterns/runtime_linux.c" patterns.elf64.o -o patterns_linux; then
            ./patterns_linux > ../actual_elf64.txt
            cd "$WORK/msvc_patterns" || exit 1
            compare expected.txt actual_elf64.txt "MSVC code patterns (elf64, native Linux)"
        else
            echo "FAIL: MSVC code patterns (elf64) - build failed"
            FAILED=1
        fi
    else
        echo "$RESULT"
        echo "FAIL: MSVC code patterns (win64) - recompilation failed"
        FAILED=1
    fi
else
    echo "FAIL: MSVC code patterns - compilation failed"
    FAILED=1
fi


# test 3: C++ exception handling data version 4 (__CxxFrameHandler4)
mkdir -p "$WORK/fh4"
cd "$WORK/fh4" || exit 1
printf 'LIBRARY "vcruntime140_1.dll"\nEXPORTS\n    __CxxFrameHandler4\n' > vcruntime140_1.def
printf 'LIBRARY "vcruntime140.dll"\nEXPORTS\n    _CxxThrowException\n' > vcruntime140.def
if nasm -f win64 "$TESTS_DIR/fh4/fh4_test.asm" -o fh4_test.obj &&
   "${CROSS}dlltool" -d vcruntime140_1.def -l libvcruntime140_1.a &&
   "${CROSS}dlltool" -d vcruntime140.def -l libvcruntime140.a &&
   "${CROSS}gcc" -nostartfiles -nostdlib -Wl,-e,start fh4_test.obj -o fh4_test.exe libvcruntime140_1.a libvcruntime140.a -lkernel32
then
    wine ./fh4_test.exe > /dev/null 2>&1; echo "exit code $?" > expected.txt
    if RESULT=$("$TESTS_DIR/roundtrip_win64.sh" fh4_test.exe "$WORK/fh4/srw64"); then
        wine "$RESULT" > /dev/null 2>&1; echo "exit code $?" > actual.txt
        compare expected.txt actual.txt "C++ exception with __CxxFrameHandler4 data (win64)"
        if python3 "$TESTS_DIR/verify_fh4.py" fh4_test.exe "$RESULT" > verify.txt; then
            echo "PASS: __CxxFrameHandler4 data verification"
        else
            cat verify.txt
            echo "FAIL: __CxxFrameHandler4 data verification"
            FAILED=1
        fi
    else
        echo "$RESULT"
        echo "FAIL: C++ exception with __CxxFrameHandler4 data - recompilation failed"
        FAILED=1
    fi
else
    echo "FAIL: C++ exception with __CxxFrameHandler4 data - compilation failed"
    FAILED=1
fi


# test 4: statically linked Linux executable (glibc: IFUNC, TLS, threads, CET, AVX-512 functions kept in original code)
mkdir -p "$WORK/linux_c"
cd "$WORK/linux_c" || exit 1
if gcc -O2 -static -no-pie -pthread -o test_linux "$TESTS_DIR/linux_c/test_linux.c" -lm 2> gcc.err; then
    ./test_linux arg1 > expected.txt 2>&1; echo "exit code $?" >> expected.txt
    if RESULT=$("$TESTS_DIR/roundtrip_elf.sh" test_linux "$WORK/linux_c/srw64"); then
        "$RESULT" arg1 > actual.txt 2>&1; echo "exit code $?" >> actual.txt
        compare expected.txt actual.txt "statically linked Linux C program (elf64)"
    else
        echo "$RESULT"
        echo "FAIL: statically linked Linux C program - recompilation failed"
        FAILED=1
    fi
else
    echo "SKIP: statically linked Linux C program - static glibc not available ($(head -1 gcc.err))"
fi


# test 5: statically linked Linux C++ program (exceptions: .eh_frame and .gcc_except_table are generated again)
mkdir -p "$WORK/linux_cpp"
cd "$WORK/linux_cpp" || exit 1
for OPT in O0 O2; do
    if g++ -$OPT -static -no-pie -pthread -o test_exceptions_$OPT "$TESTS_DIR/linux_cpp/test_exceptions.cpp" 2> gcc.err; then
        ./test_exceptions_$OPT > expected_$OPT.txt 2>&1; echo "exit code $?" >> expected_$OPT.txt
        if RESULT=$("$TESTS_DIR/roundtrip_elf.sh" test_exceptions_$OPT "$WORK/linux_cpp/srw64_$OPT"); then
            "$RESULT" > actual_$OPT.txt 2>&1; echo "exit code $?" >> actual_$OPT.txt
            compare expected_$OPT.txt actual_$OPT.txt "statically linked Linux C++ program with exceptions (-$OPT, elf64)"
        else
            echo "$RESULT"
            echo "FAIL: statically linked Linux C++ program (-$OPT) - recompilation failed"
            FAILED=1
        fi
    else
        echo "SKIP: statically linked Linux C++ program - static libstdc++ not available ($(head -1 gcc.err))"
        break
    fi
done


# test 6 (optional): verification of __CxxFrameHandler4 data in executables built by Visual Studio 2019+
if [ -n "$FH4_EXECUTABLES" ]; then
    mkdir -p "$WORK/fh4_executables"
    cd "$WORK/fh4_executables" || exit 1
    for EXE in $FH4_EXECUTABLES; do
        NAME=$(basename "$EXE" .exe)
        if RESULT=$("$TESTS_DIR/roundtrip_win64.sh" "$EXE" "$WORK/fh4_executables/$NAME"); then
            if python3 "$TESTS_DIR/verify_fh4.py" "$EXE" "$RESULT" > "$NAME.verify.txt"; then
                echo "PASS: __CxxFrameHandler4 data in $NAME.exe ($(tail -1 "$NAME.verify.txt"))"
            else
                cat "$NAME.verify.txt"
                echo "FAIL: __CxxFrameHandler4 data in $NAME.exe"
                FAILED=1
            fi
        else
            echo "$RESULT"
            echo "FAIL: $NAME.exe - recompilation failed"
            FAILED=1
        fi
    done
fi


# test 7 (optional): Windows executables (built by Microsoft with MSVC)
if [ -n "$WINDOWS_DIR" ]; then
    mkdir -p "$WORK/windows"
    cd "$WORK/windows" || exit 1
    printf 'banana\napple\ncherry\nApple pie\n42\n' > input.txt
    for NAME in sort where; do
        if [ ! -f "$WINDOWS_DIR/$NAME.exe" ]; then
            echo "SKIP: $NAME.exe not found in $WINDOWS_DIR"
            continue
        fi
        cp "$WINDOWS_DIR/$NAME.exe" . || continue
        if RESULT=$("$TESTS_DIR/roundtrip_win64.sh" $NAME.exe "$WORK/windows/$NAME"); then
            case $NAME in
                sort) ARGS_LIST="input.txt|/R input.txt|/+2 input.txt|nonexistent.txt" ;;
                where) ARGS_LIST="notepad|/T notepad|nosuchprogram" ;;
            esac
            OLD_IFS=$IFS
            IFS='|'
            for ARGS in $ARGS_LIST; do
                IFS=$OLD_IFS
                wine ./$NAME.exe $ARGS > expected.txt 2> /dev/null; echo "exit code $?" >> expected.txt
                wine "$RESULT" $ARGS > actual.txt 2> /dev/null; echo "exit code $?" >> actual.txt
                compare expected.txt actual.txt "$NAME.exe $ARGS (win64)"
                IFS='|'
            done
            IFS=$OLD_IFS
        else
            echo "$RESULT"
            echo "FAIL: $NAME.exe - recompilation failed"
            FAILED=1
        fi
    done
fi

if [ $FAILED -eq 0 ]; then
    echo "All tests passed"
else
    echo "Some tests failed (work directory: $WORK)"
fi

exit $FAILED
