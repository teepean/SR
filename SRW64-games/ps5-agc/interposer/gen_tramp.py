#! /usr/bin/env python3
# generates ysr_tramp.S and ysr_names.h from agc_imports.txt (<NID> <name>)
import sys

def category(name):
    if name.endswith('PushMarker'): return 'CAT_PUSH'
    if name.endswith('PopMarker'): return 'CAT_POP'
    if name in ('sceAgcCbDispatch', 'sceAgcAcbDispatchIndirect', 'sceAgcDcbDispatchIndirect'): return 'CAT_DISPATCH'
    if name.startswith('sceAgcDcbDraw'): return 'CAT_DRAW'
    if any(name.endswith(s) for s in ('AcquireMem', 'EventWrite', 'WaitRegMem', 'ReleaseMem', 'WaitUntilSafeForRendering', 'StallCommandBufferParser', 'CondExec', 'DmaData', 'WriteData')) and 'Patch' not in name: return 'CAT_SYNC'
    if 'Submit' in name: return 'CAT_SUBMIT'
    if name.endswith('SetFlip'): return 'CAT_FLIP'
    return 'CAT_OTHER'

entries = [line.split() for line in open(sys.argv[1]) if line.strip()]
with open('ysr_names.h', 'w') as h:
    h.write('// generated by gen_tramp.py\n#define YSR_NUM_FUNCS %d\n' % len(entries))
    h.write('static const char *const ysr_nids[YSR_NUM_FUNCS] = {\n%s};\n' % ''.join('    "%s",\n' % e[0] for e in entries))
    h.write('static const char *const ysr_names[YSR_NUM_FUNCS] = {\n%s};\n' % ''.join('    "%s",\n' % e[1] for e in entries))
    h.write('static const int ysr_categories[YSR_NUM_FUNCS] = {\n%s};\n' % ''.join('    %s,\n' % category(e[1]) for e in entries))
with open('ysr_tramp.S', 'w') as s:
    s.write('# generated by gen_tramp.py: interposers for imported sceAgc* functions\n')
    s.write('\t.intel_syntax noprefix\n\t.text\n')
    for index, (nid, name) in enumerate(entries):
        s.write('''
\t.globl "%(nid)s"
\t.type "%(nid)s", @function
"%(nid)s":                              # %(name)s
\tpush rdi
\tpush rsi
\tpush rdx
\tpush rcx
\tpush r8
\tpush r9
\tpush rax
\tmov edi, %(index)d
\tmov rsi, [rsp + 48]
\tmov rdx, [rsp + 40]
\tmov rcx, [rsp + 56]
\tmov r8, rsp                         # saved registers: rax r9 r8 rcx rdx rsi rdi (the hook can change arguments)
\tmov r9, rbp                         # frame of the caller (YSR_HELPER: caller of the game's helper)
\tcall ysr_hook
\tpop rax
\tpop r9
\tpop r8
\tpop rcx
\tpop rdx
\tpop rsi
\tpop rdi
\tjmp [rip + ysr_real + %(offset)d]
\t.size "%(nid)s", . - "%(nid)s"
''' % {'nid': nid, 'name': name, 'index': index, 'offset': 8 * index})
    s.write('\t.section .note.GNU-stack,"",@progbits\n')
